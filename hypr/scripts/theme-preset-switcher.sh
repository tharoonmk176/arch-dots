hex_to_rgb_csv() {
    local input=$1
    local hex

    hex=${input#rgba(}
    hex=${hex%)}
    hex=${hex#\#}
    if [ "${#hex}" -eq 8 ]; then
        hex=${hex:0:6}
    fi
    printf '%d, %d, %d' "0x${hex:0:2}" "0x${hex:2:2}" "0x${hex:4:2}"
}

# Apply theme
apply_theme() {
    local theme=$1
    local theme_file="$THEME_DIR/$theme.conf"

    if [ ! -f "$theme_file" ]; then
        echo "Error: Theme '$theme' not found in $THEME_DIR"
        return 1
    fi

    # Copy theme colors to colors.conf
    cp "$theme_file" "$COLORS_CONF"

    # Add metadata
    {
        echo ""
        echo "# Theme: $theme"
        echo "\$theme_name = $theme"
    } >> "$COLORS_CONF"

    # Extract colors
    local background=$(parse_color "background" "$theme_file")
    local surface=$(parse_color "surface" "$theme_file")
    local foreground=$(parse_color "foreground" "$theme_file")
    local readable_foreground=$(parse_color "readable_foreground" "$theme_file")
    local primary=$(parse_color "primary" "$theme_file")
    local secondary=$(parse_color "secondary" "$theme_file")
    local tertiary=$(parse_color "tertiary" "$theme_file")
    local accent=$(parse_color "accent" "$theme_file")
    local error=$(parse_color "error" "$theme_file")
    local success=$(parse_color "success" "$theme_file")
    local warning=$(parse_color "warning" "$theme_file")

    BACKGROUND="$background"
    SURFACE="$surface"
    FOREGROUND="$foreground"
    READABLE_TEXT="$readable_foreground"
    PRIMARY="$primary"
    SECONDARY="$secondary"
    TERTIARY="$tertiary"
    ACCENT="$accent"
    ERROR="$error"
    SUCCESS="$success"
    WARNING="$warning"
    SURFACE_CONTAINER="$surface"

    write_waybar_theme
    write_kitty_theme
    write_rofi_theme
    write_gtk_theme
    # write_wlogout_theme
    write_swaync_theme
    write_hyprlock_from_preset

    reload_waybar
    pkill -SIGUSR1 kitty 2>/dev/null || true
    swaync-client -rs 2>/dev/null || true

    # Save current theme
    echo "$theme" > "$CURRENT_THEME_FILE"

    # Reload Hyprland config (re-reads appearance.lua with new colors)
    hyprctl reload >/dev/null 2>&1 || true

    notify-send "Theme preset" "$theme" 2>/dev/null || true
    echo "Theme applied: $theme"
}

hyprlock_rgb_from_rgba() {
    local input=$1
