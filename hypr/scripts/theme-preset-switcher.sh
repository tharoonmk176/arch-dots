#!/usr/bin/env bash

set -euo pipefail

THEME_DIR="$HOME/.config/hypr/themes"
COLORS_CONF="$HOME/.config/hypr/colors.conf"
APPEARANCE_LUA="$HOME/.config/hypr/conf/appearance.lua"
CURRENT_THEME_FILE="$HOME/.cache/hyprland-current-theme"

WAYBAR_STYLE="$HOME/.config/waybar/style.css"
