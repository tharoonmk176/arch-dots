reload_waybar() {
    pkill -SIGUSR2 waybar 2>/dev/null || {
        pkill waybar 2>/dev/null || true
        waybar >/dev/null 2>&1 &
    }
}

# Show theme picker UI
show_picker() {
    local themes=($(list_themes))
    local current=$(get_current_theme)
    local selected

    if command -v rofi >/dev/null 2>&1; then
        local -a displays=()
        for theme in "${themes[@]}"; do
            local theme_file="$THEME_DIR/$theme.conf"
            local primary=$(parse_color "primary" "$theme_file")
            local accent=$(parse_color "accent" "$theme_file")
            local background=$(parse_color "background" "$theme_file")
            
            local p_hex=$(color_hex "$primary")
            local a_hex=$(color_hex "$accent")
            local b_hex=$(color_hex "$background")
            
            local color_info="<span foreground=\"$p_hex\">■</span><span foreground=\"$a_hex\">■</span><span foreground=\"$b_hex\">■</span>"
            displays+=("$(printf '%-20s %s' "$theme" "$color_info")")
        done
        local selected_index
        selected_index=$(printf '%s\n' "${displays[@]}" | rofi -dmenu -i -p "Select Theme" -markup-rows -format i) || return 1
        [[ "$selected_index" =~ ^[0-9]+$ ]] || return 1
        selected="${themes[$selected_index]}"
    elif command -v fzf >/dev/null 2>&1 && [ -t 0 ]; then
        selected=$(printf '%s\n' "${themes[@]}" | fzf --prompt="Theme> " --height=40% --reverse --border)
    else
        echo "Available themes:"
        for i in "${!themes[@]}"; do
            printf "%d) %s%s\n" $((i+1)) "${themes[$i]}" "$([ "${themes[$i]}" = "$current" ] && echo ' (current)' || echo '')"
        done
        read -p "Select theme (number or name): " selected
    fi

    [ -n "$selected" ] && apply_theme "$selected"
}

main() {
    case "${1:-}" in
        list)
            echo "Available themes:"
            for theme in $(list_themes); do
                current=$(get_current_theme)
                [ "$theme" = "$current" ] && echo "  ✓ $theme" || echo "    $theme"
            done
            ;;
        current)
            get_current_theme
            ;;
        apply)
            [ -z "${2:-}" ] && { echo "Usage: $0 apply <theme>"; exit 1; }
            apply_theme "$2"
            ;;
        *)
            show_picker
            ;;
    esac
}

main "$@"
