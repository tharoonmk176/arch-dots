# List available themes
list_themes() {
    find "$THEME_DIR" -name "*.conf" -type f | xargs -I {} basename {} .conf | sort
}

# Get current theme
get_current_theme() {
    if [ -f "$CURRENT_THEME_FILE" ]; then
        cat "$CURRENT_THEME_FILE"
    else
        echo "custom"
    fi
}

# Parse color from theme file
parse_color() {
    local var=$1
    local theme_file=$2
    grep "^\\\$$var =" "$theme_file" | sed 's/^[^=]*= //g' | tr -d ' "' || echo "rgba(595959aa)"
}

# Convert Hypr rgba(...) or #rrggbbaa values to plain hex (#rrggbb)
color_hex() {
    local input=${1//[[:space:]]/}
    input=${input#rgba(}
    input=${input%)}
    input=${input#\#}
    if [ "${#input}" -eq 8 ]; then
        input=${input:0:6}
    fi
    printf '#%s' "$input"
}

# Convert Hypr rgba(...) or #rrggbbaa values to hex with alpha (#rrggbbaa)
color_hexalpha() {
    local input=${1//[[:space:]]/}
    input=${input#rgba(}
    input=${input%)}
    input=${input#\#}
    if [ "${#input}" -eq 6 ]; then
        printf '#%sff' "$input"
    else
        printf '#%s' "$input"
    fi
}

write_waybar_theme() {
    mkdir -p "$(dirname "$WAYBAR_COLORS")"
    local background_hex=$(color_hex "$BACKGROUND")
    local surface_hex=$(color_hex "$SURFACE")
    local surface_container_hex=$(color_hex "$SURFACE_CONTAINER")
    local text_hex=$(color_hex "$PRIMARY")
    local readable_text_hex=$(color_hex "$READABLE_TEXT")
    local on_text_hex=$(color_hex "$FOREGROUND")
    local secondary_hex=$(color_hex "$SECONDARY")
    local tertiary_hex=$(color_hex "$TERTIARY")
