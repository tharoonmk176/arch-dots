@define-color on_text $on_text_hex;
@define-color secondary $secondary_hex;
@define-color tertiary $tertiary_hex;
@define-color error $error_hex;
@define-color warning $(color_hex "$WARNING");
@define-color success $(color_hex "$SUCCESS");
@define-color chip $surface_container_hex;
@define-color chip_border $surface_hex;
EOF
}

